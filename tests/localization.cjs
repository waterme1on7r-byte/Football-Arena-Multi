const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const cfg = require('../settings');
const prior = cfg.normalize({ restore: false, chat: {nick:'Tester'}, net: {dpiPreset:3} });
assert.equal(prior.language,'tr');
assert.equal(prior.languageChosen,false);
const changed = cfg.merge(prior,{language:'en',languageChosen:true});
assert.equal(changed.language,'en');
assert.equal(changed.restore,false);
assert.equal(changed.chat.nick,'Tester');
assert.equal(changed.net.dpiPreset,3);
assert.equal(cfg.merge(changed,{language:'invalid'}).language,'tr');
const context = {document:{readyState:'loading',addEventListener(){}},arena:{cfg:{language:'tr'}}};
vm.createContext(context);
for (const path of ['renderer/translations.js','renderer/i18n.js']) vm.runInContext(fs.readFileSync(path,'utf8'),context);
assert.equal(context.FA_I18N.t('Settings'),'Ayarlar');
assert.equal(context.FA_I18N.t('Version 1.8.12 is ready.'),'1.8.12 sürümü hazır.');
assert.equal(context.FA_I18N.t('Too many tries. Wait 30 s.'),'Çok fazla deneme. 30 saniye bekleyin.');
assert.equal(context.FA_I18N.t('https://example.com/app'),'https://example.com/app');
assert.equal(context.FA_I18N.t('Football Arena'),'Football Arena');
const native = JSON.parse(fs.readFileSync('android/app/src/main/assets/i18n-tr.json','utf8'));
assert.deepEqual(JSON.parse(JSON.stringify(context.FA_TRANSLATIONS)),native);
console.log('Localization and settings migration checks passed');
