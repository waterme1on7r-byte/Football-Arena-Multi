const { contextBridge, ipcRenderer } = require("electron");
contextBridge.exposeInMainWorld("arena", {
  update: list => ipcRenderer.send("views:update", list),
  navigate: (id, url) => ipcRenderer.send("view:navigate", id, url),
  reload: id => ipcRenderer.send("view:reload", id),
  overlay: on => ipcRenderer.send("overlay", !!on),
  exportSites: text => ipcRenderer.invoke("sites:export", text),
  importSites: () => ipcRenderer.invoke("sites:import"),
  onUrl: cb => ipcRenderer.on("tab:url", (_e, d) => cb(d)),
  onOpen: cb => ipcRenderer.on("tab:open", (_e, d) => cb(d)),
  perf: () => ipcRenderer.invoke("app:perf"),
  remoteSites: manual => ipcRenderer.invoke("sites:remote", !!manual),
  remoteCached: () => ipcRenderer.invoke("sites:cached"),
  health: url => ipcRenderer.invoke("health:check", url),
  chatConfig: () => ipcRenderer.invoke("chat:config"),
  chatToggle: () => ipcRenderer.send("chat:toggle"),
  onChatState: cb => ipcRenderer.on("chat:state", (_e, d) => cb(d)),
  onChatUnread: cb => ipcRenderer.on("chat:unread", (_e, d) => cb(d)),
  freeze: () => ipcRenderer.invoke("overlay:freeze"),
  dpiStatus: () => ipcRenderer.invoke("dpi:status"),
  dpiRetry: () => ipcRenderer.send("dpi:retry"),
  dpiStop: () => ipcRenderer.send("dpi:stop"),
  onDpi: cb => ipcRenderer.on("dpi:status", (_e, d) => cb(d)),
  onRelayout: cb => ipcRenderer.on("relayout", () => cb()),
  // settings (saved in the user data folder by the app; this is a copy taken when the window opens)
  cfg: ipcRenderer.sendSync("settings:get"),
  setCfg: patch => ipcRenderer.invoke("settings:set", patch),
  onCfg: cb => ipcRenderer.on("settings:changed", (_e, d) => cb(d)),
  focusPane: id => ipcRenderer.send("view:focus", id),
  onFocus: cb => ipcRenderer.on("pane:focus", (_e, id) => cb(id)),
  // parental passcode + kill switch
  lockTry: code => ipcRenderer.invoke("lock:try", code),
  lockSet: (current, next) => ipcRenderer.invoke("lock:set", { current, next }),
  onLock: cb => ipcRenderer.on("lock:state", (_e, v) => cb(!!v)),
  onBlocked: cb => ipcRenderer.on("app:blocked", (_e, d) => cb(d)),
  // app
  openLogs: () => ipcRenderer.invoke("app:openLogs"),
  resetAll: code => ipcRenderer.invoke("app:reset", code),
  updStatus: () => ipcRenderer.invoke("updater:status"),
  updCheck: () => ipcRenderer.invoke("updater:check"),
  updRelease: () => ipcRenderer.invoke("updater:release"),
  updInstall: () => ipcRenderer.invoke("updater:install"),
  onUpd: cb => ipcRenderer.on("updater:state", (_e, d) => cb(d)),
  // network
  blocklistRead: () => ipcRenderer.invoke("blocklist:read"),
  blocklistWrite: text => ipcRenderer.invoke("blocklist:write", text),
  // chat (ban list is for admins only: the chat window reports whether the admin password was entered)
  chatAdmin: () => ipcRenderer.invoke("chat:adminState"),
  onChatAdmin: cb => ipcRenderer.on("chat:admin", (_e, d) => cb(d)),
  chatUnban: u => ipcRenderer.send("chat:unban", u),
});
